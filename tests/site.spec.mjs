import { test, expect } from '@playwright/test';

test('loads assets, starts the game, changes settings and ships, and restores settings', async ({ page }) => {
  const errors = [];
  const failures = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
  await page.goto('./');
  await expect(page.locator('.title-screen')).toBeVisible();
  await expect(page.locator('.loading-screen-container')).toBeHidden({ timeout: 20000 });
  await page.locator('.start-button').click();
  await expect(page.locator('.app-contents')).toBeVisible({ timeout: 20000 });
  await expect(page.locator('.loading-screen-container')).toBeHidden({ timeout: 20000 });
  await expect(page.locator('canvas[id^="ship-"]')).toBeVisible();
  await page.locator('.settings-button').click();
  await expect(page.getByRole('heading', { name: 'Volume', exact: true })).toBeVisible();
  await page.locator('input[type=range]').first().fill('40');
  await expect.poll(() => page.evaluate(() => localStorage.getItem('overallVolume'))).toBe('0.4');
  await page.getByRole('button', { name: 'Change BGM', exact: true }).click();
  await page.locator('.list-item').nth(1).click();
  await expect(page.locator('.list-item').nth(1)).toHaveClass(/selected/);
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.locator('.composition-button').click();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.locator('.card').first().click();
  await expect.poll(() => page.evaluate(() => localStorage.getItem('selectedShipName'))).not.toBe('"Yamato"');
  await expect(page.locator('canvas[id^="ship-"]')).toBeVisible();
  await page.screenshot({ path: test.info().outputPath('game.png') });
  await page.reload();
  await expect(page.locator('.loading-screen-container')).toBeHidden({ timeout: 20000 });
  await page.locator('.start-button').click();
  await expect(page.locator('.app-contents')).toBeVisible({ timeout: 20000 });
  await expect(page.locator('.loading-screen-container')).toBeHidden({ timeout: 20000 });
  await page.locator('.settings-button').click();
  await expect(page.locator('input[type=range]').first()).toHaveValue('40');
  expect(errors).toEqual([]);
  expect(failures).toEqual([]);
});
